// Regenerates Source/App/Patches.inc from lab/patches.js so the app and the browser lab share one patch list.
// Usage: node tools/gen_patches.js
const path = require('path'), fs = require('fs');
const { BASE, PATCHES, BANDS, makePatch } = require(path.join(__dirname, '..', 'lab', 'patches.js'));
const raw = s => 'R"SILTJSON(' + s + ')SILTJSON"';
let out = '// Generated by tools/gen_patches.js from lab/patches.js. Do not edit by hand.\n#pragma once\n';
out += 'static const char* kBaseJson = ' + raw(JSON.stringify(BASE)) + ';\n';
out += 'static const char* kBandPresetsJson = ' + raw(JSON.stringify(BANDS)) + ';\n';
out += 'struct FactoryPatch { const char* name; const char* json; const char* notes; };\n';
out += 'static const FactoryPatch kFactoryPatches[] = {\n';
for (const name of Object.keys(PATCHES)) { const p = makePatch(name);
  out += '  { ' + raw(name) + ', ' + raw(JSON.stringify({ silt: 2, name, P: p.P, S: p.S })) + ', ' + raw(JSON.stringify(PATCHES[name].notes)) + ' },\n'; }
out += '};\n';
fs.writeFileSync(path.join(__dirname, '..', 'Source', 'App', 'Patches.inc'), out);
console.log('wrote', Object.keys(PATCHES).length, 'patches');
